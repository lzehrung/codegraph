import path from "node:path";

export const DUPLICATE_IDENTIFIER_RANGES_TARGET = path.resolve("src/duplicate-identifier-ranges.ts");

// The native tokenizer classifies ASCII the same way in every Unicode version, and probing it
// there is ambiguous: quotes open string literals and digits open numeric literals, so a probe
// cannot tell "literal starter" from "identifier starter". Assert the ASCII grammar instead.
const ASCII_LIMIT = 0x80;
const MAX_CODE_POINT = 0x10ffff;
const SURROGATE_START = 0xd800;
const SURROGATE_END = 0xdfff;
// Any character that is both an identifier start and an identifier continue works as the probe
// anchor. 'A' keeps the probe strings short and never combines with the code point under test.
const PROBE_ANCHOR = "A";

function isAsciiIdentifierStart(codePoint) {
  return /[A-Za-z_$]/.test(String.fromCodePoint(codePoint));
}

function isAsciiIdentifierContinue(codePoint) {
  return /[A-Za-z0-9_$]/.test(String.fromCodePoint(codePoint));
}

/**
 * Reads both identifier predicates for one code point out of the native tokenizer. Wrapping the
 * code point in anchors separates the three outcomes: a continuation character merges into one
 * identifier token, whitespace splits the anchors into two, and anything else becomes its own
 * third token.
 */
function classifyCodePoint(tokenize, codePoint) {
  const character = String.fromCodePoint(codePoint);
  const continueTokens = tokenize(`${PROBE_ANCHOR}${character}${PROBE_ANCHOR}`);
  const isContinue = continueTokens.length === 1;
  const isWhitespace = continueTokens.length === 2;
  const isStart = !isWhitespace && tokenize(`${character}${PROBE_ANCHOR}`).length === 1;
  return { isStart, isContinue };
}

function collectRanges(predicate) {
  const ranges = [];
  let start = -1;
  for (let codePoint = 0; codePoint <= MAX_CODE_POINT; codePoint += 1) {
    const included = codePoint >= SURROGATE_START && codePoint <= SURROGATE_END ? false : predicate(codePoint);
    if (included && start < 0) start = codePoint;
    if (!included && start >= 0) {
      ranges.push([start, codePoint - 1]);
      start = -1;
    }
  }
  if (start >= 0) ranges.push([start, MAX_CODE_POINT]);
  return ranges;
}

/**
 * Derives the duplicate-tokenizer identifier ranges from a native tokenizer. `tokenize` takes a
 * source string and returns its normalized tokens.
 */
export function collectDuplicateIdentifierRanges(tokenize) {
  const startByCodePoint = new Uint8Array(MAX_CODE_POINT + 1);
  const continueByCodePoint = new Uint8Array(MAX_CODE_POINT + 1);

  for (let codePoint = 0; codePoint < ASCII_LIMIT; codePoint += 1) {
    startByCodePoint[codePoint] = isAsciiIdentifierStart(codePoint) ? 1 : 0;
    continueByCodePoint[codePoint] = isAsciiIdentifierContinue(codePoint) ? 1 : 0;
  }

  for (let codePoint = ASCII_LIMIT; codePoint <= MAX_CODE_POINT; codePoint += 1) {
    if (codePoint >= SURROGATE_START && codePoint <= SURROGATE_END) continue;
    const { isStart, isContinue } = classifyCodePoint(tokenize, codePoint);
    startByCodePoint[codePoint] = isStart ? 1 : 0;
    continueByCodePoint[codePoint] = isContinue ? 1 : 0;
  }

  // The ASCII grammar is asserted rather than probed, so prove the assertion against the native
  // tokenizer for the characters it can answer unambiguously.
  for (let codePoint = 0; codePoint < ASCII_LIMIT; codePoint += 1) {
    if (!/[A-Za-z0-9_$]/.test(String.fromCodePoint(codePoint))) continue;
    const { isStart, isContinue } = classifyCodePoint(tokenize, codePoint);
    if (isStart !== Boolean(startByCodePoint[codePoint]) || isContinue !== Boolean(continueByCodePoint[codePoint])) {
      throw new Error(`Native tokenizer disagrees with the asserted ASCII grammar at U+${codePoint.toString(16)}.`);
    }
  }

  return {
    startRanges: collectRanges((codePoint) => Boolean(startByCodePoint[codePoint])),
    continueRanges: collectRanges((codePoint) => Boolean(continueByCodePoint[codePoint])),
  };
}

function renderRanges(ranges) {
  return ranges.map(([from, to]) => `  [0x${from.toString(16)}, 0x${to.toString(16)}],`).join("\n");
}

export function renderDuplicateIdentifierRanges({ startRanges, continueRanges }) {
  return `// Generated by scripts/generate-duplicate-identifier-ranges.mjs from the pinned
// \`unicode-ident\` crate in packages/codegraph-native. Do not edit by hand.
//
// The duplicate tokenizer fingerprints source text, so its identifier grammar must not shift
// under either implementation. Resolving \\p{XID_Start} at runtime would tie the TypeScript
// fallback to whichever Unicode version the host Node build embeds, which drifts from the
// version the native tokenizer is pinned to. These ranges freeze that grammar instead.

/** Inclusive code point ranges accepted as the first character of a duplicate-tokenizer identifier. */
export const DUPLICATE_IDENTIFIER_START_RANGES: ReadonlyArray<readonly [number, number]> = [
${renderRanges(startRanges)}
];

/** Inclusive code point ranges accepted after the first character of a duplicate-tokenizer identifier. */
export const DUPLICATE_IDENTIFIER_CONTINUE_RANGES: ReadonlyArray<readonly [number, number]> = [
${renderRanges(continueRanges)}
];
`;
}
