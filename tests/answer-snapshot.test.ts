import fs from "node:fs";
import path from "node:path";
import { afterEach, describe, expect, it, vi } from "vitest";
import {
  answerProjectRecords,
  assertAnswerScratchDirectory,
  discoverAnswerRoots,
  discoverPinnedAnswerRoots,
  generateAnswerSnapshots,
  loadAnswerApi,
  runAnswerSnapshots,
  updateAnswerSnapshots,
} from "../scripts/answer-snapshot-lib.mjs";
import type { AnswerProject } from "../scripts/answer-snapshot-lib.mjs";
import { createTempRootRegistry, isSymlinkUnavailable } from "./helpers/filesystem.js";
import { runGit } from "./helpers/git.js";
import { absoluteSnapshotPathPatterns } from "../scripts/snapshot-paths-lib.mjs";

const roots = createTempRootRegistry();
const api = await loadAnswerApi();
afterEach(async () => {
  vi.restoreAllMocks();
  await roots.cleanup();
});

async function project(sources: Record<string, string>, prefix = "") {
  const directory = await roots.create("cg-answer-snapshot-");
  for (const [name, source] of Object.entries(sources)) {
    fs.mkdirSync(path.dirname(path.join(directory, name)), { recursive: true });
    fs.writeFileSync(path.join(directory, name), source);
  }
  return { directory, prefix, label: "test-project" };
}

function group(entry: AnswerProject) {
  return [{ name: "test", description: "test-project", projects: [entry] }];
}

const source = "export function caf\u00e9() { return 1; }\n";
const consumer = 'import { caf\u00e9 as alias } from "./source";\nalias();\nmissing();\n';
const generatedHeader = "# Generated by `npm run answers:snapshot`;\n";
const snapshotDist = path.resolve("dist");

async function pinnedProject() {
  const corpusDir = await roots.create("cg-answer-pins-");
  const directory = path.join(corpusDir, "tiny");
  fs.mkdirSync(directory);
  fs.writeFileSync(path.join(directory, "tracked.ts"), "export const value = 1;\nvalue;\n");
  runGit(directory, ["init"]);
  runGit(directory, ["add", "."]);
  runGit(directory, ["commit", "-m", "pin snapshot fixture"]);
  const commit = runGit(directory, ["rev-parse", "HEAD"]);
  const manifest = [{ id: "tiny", family: "fixture", commit, include: ["*.ts"], exclude: ["ignored/**"] }];
  return { corpusDir, directory, manifest };
}

describe("cross-language answer snapshots", () => {
  it("records actual goto targets, misses, declarations and exact references without checkout identity", async () => {
    const entry = await project({ "source.ts": source, "consumer.ts": consumer });
    const snapshots = await generateAnswerSnapshots(api, group(entry));
    const text = snapshots.get("test.txt")!;
    expect(text).toContain('goto consumer.ts:2:1 "alias" -> ok source.ts:1:17-1:21 function "caf\\u{e9}"');
    expect(text).toContain('goto consumer.ts:3:1 "missing" -> not_found ');
    expect(text).toContain('refs source.ts:1:17-1:21 function "caf\\u{e9}" -> ok source.ts:1:17-1:21');
    expect(text).toContain("coverage=complete scope=indexed_candidates reasons=[] affected=[]");
    expect(text).toContain('ref source.ts:1:17-1:21 function "caf\\u{e9}" -> consumer.ts:2:1-2:6');
    expect(text).not.toContain(entry.directory);
    expect(text).not.toMatch(/[^\x20-\x7e\n]/u);
    const records = text
      .trimEnd()
      .split("\n")
      .filter((line) => !line.startsWith("#"));
    expect(records).toEqual([...records].sort());
    const fileSummaries = records.filter((line) => line.startsWith("file "));
    const declarationCount = fileSummaries.reduce((sum, line) => sum + Number(/declarations=(\d+)/.exec(line)![1]), 0);
    const identifierCount = fileSummaries.reduce((sum, line) => sum + Number(/identifiers=(\d+)/.exec(line)![1]), 0);
    expect(records.filter((line) => line.startsWith("refs "))).toHaveLength(declarationCount);
    expect(records.filter((line) => line.startsWith("goto "))).toHaveLength(identifierCount);
  });

  it("is byte-identical after relocation and reversed creation order", async () => {
    const first = await project({ "source.ts": source, "consumer.ts": consumer }, "scenario/");
    const second = await project({ "consumer.ts": consumer, "source.ts": source }, "scenario/");
    const before = await generateAnswerSnapshots(api, group(first));
    const after = await generateAnswerSnapshots(api, group(second));
    expect(after).toEqual(before);
    expect(after.get("test.txt")).toContain("goto scenario/consumer.ts:2:1");
  });

  it("records real partial coverage reasons and affected files separately from a confident miss", async () => {
    const entry = await project({
      "box.js": [
        "class Box {",
        "  helper() {}",
        "  run() {",
        "    function nested() { this.helper(); }",
        "    const arrow = () => this.helper();",
        "  }",
        "}",
      ].join("\n"),
    });
    const records: string[] = await answerProjectRecords(api, entry);
    const summary = records.find((line) => line.startsWith('refs box.js:2:3-2:9 function "helper"'));
    expect(summary).toContain(
      'coverage=partial scope=indexed_candidates reasons=["strategy_unavailable"] affected=["box.js"]',
    );
    expect(
      records.some((line) => line.startsWith('ref box.js:2:3-2:9 function "helper" -> box.js:5:30-5:36 order=')),
    ).toBe(true);
    expect(
      records.some((line) => line.startsWith('ref box.js:2:3-2:9 function "helper" -> box.js:4:30-4:36 order=')),
    ).toBe(false);
  });

  it("keeps unsupported syntax explicit and records non-code reference misses", async () => {
    const entry = await project({
      "data.json": '{"answer": 42}\n',
      "main.ts": 'import data from "./data.json";\ndata.answer;\n',
    });
    const records: string[] = await answerProjectRecords(api, entry);
    expect(records).toContain(
      'file data.json language=unsupported identifiers=0 declarations=1 syntax=unsupported UnsupportedParserInputError "Unsupported file extension: data.json"',
    );
    expect(records).toContain(
      'refs data.json:1:1-1:1 default "default" -> not_found "Reference collection is unavailable for non-code targets"',
    );
  });

  it("discovers every sample project and every edge scenario using the graph snapshot grouping", () => {
    const discovered = discoverAnswerRoots();
    const samples = fs
      .readdirSync("tests/samples", { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .sort();
    expect(discovered.filter((root) => !root.name.startsWith("edge-corpus-")).map((root) => root.name)).toEqual(
      samples,
    );
    for (const root of discovered.filter((entry) => entry.name.startsWith("edge-corpus-"))) {
      const language = root.name.slice("edge-corpus-".length);
      const scenarios = fs
        .readdirSync(path.join("tests/edge-corpus", language), { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => entry.name)
        .sort()
        .map((name) => `${name}/`);
      expect(root.projects.map((entry) => entry.prefix)).toEqual(scenarios);
    }
  });

  it("fails read-only comparison on real answer changes, prints a bounded diff, and regenerates", async () => {
    const entry = await project({ "source.ts": source, "consumer.ts": consumer });
    const before = await generateAnswerSnapshots(api, group(entry));
    const output = await roots.create("cg-answer-output-");
    const log = vi.spyOn(console, "log").mockImplementation(() => {});
    const error = vi.spyOn(console, "error").mockImplementation(() => {});
    updateAnswerSnapshots(before, output);
    const file = path.join(output, "test.txt");
    const original = fs.readFileSync(file, "utf8");
    fs.writeFileSync(path.join(entry.directory, "source.ts"), "export function replacement() { return 1; }\n");
    const after = await generateAnswerSnapshots(api, group(entry));
    expect(() => updateAnswerSnapshots(after, output, true)).toThrow(
      /Answer snapshot is stale.*npm run answers:snapshot/,
    );
    const diff = error.mock.calls.flat().join("\n");
    expect(diff).toContain("test.txt: answers differ");
    expect(diff).toContain("  - goto consumer.ts:2:1");
    expect(diff).toContain("  + goto consumer.ts:2:1");
    expect(fs.readFileSync(file, "utf8")).toBe(original);
    updateAnswerSnapshots(after, output);
    expect(() => updateAnswerSnapshots(after, output, true)).not.toThrow();
    expect(log.mock.calls.flat().join("\n")).toContain("Answer snapshot is up to date (1 files).");
  });

  it("rejects missing, obsolete and layout-only changes without rewriting them in check mode", async () => {
    const output = await roots.create("cg-answer-output-");
    vi.spyOn(console, "log").mockImplementation(() => {});
    const error = vi.spyOn(console, "error").mockImplementation(() => {});
    const snapshots = new Map([["test.txt", `${generatedHeader}a\nb\n`]]);
    expect(() => updateAnswerSnapshots(snapshots, output, true)).toThrow(/stale/);
    expect(fs.existsSync(path.join(output, "test.txt"))).toBe(false);
    updateAnswerSnapshots(snapshots, output);
    fs.writeFileSync(path.join(output, "test.txt"), `${generatedHeader}b\na\n`);
    expect(() => updateAnswerSnapshots(snapshots, output, true)).toThrow(/stale/);
    expect(error.mock.calls.flat().join("\n")).toContain("different order");
    fs.writeFileSync(path.join(output, "obsolete.txt"), `${generatedHeader}old\n`);
    fs.writeFileSync(path.join(output, "keep.json"), "{}\n");
    expect(() => updateAnswerSnapshots(snapshots, output, true)).toThrow(/2 file\(s\) differ/);
    updateAnswerSnapshots(snapshots, output);
    expect(fs.existsSync(path.join(output, "obsolete.txt"))).toBe(false);
    expect(fs.existsSync(path.join(output, "keep.json"))).toBe(true);
  });

  it("requires explicit external scratch and rejects output overlapping source, dist or a corpus", async () => {
    const corpus = await roots.create("cg-answer-corpus-");
    const output = await roots.create("cg-answer-output-");
    const dist = path.resolve("dist");
    expect(() => assertAnswerScratchDirectory(path.resolve("tests/snapshots/answers"), [corpus], dist)).toThrow(
      /scratch --dir outside/,
    );
    expect(() => assertAnswerScratchDirectory(path.join(corpus, "nested"), [corpus], dist)).toThrow(
      /scratch --dir outside/,
    );
    expect(() => assertAnswerScratchDirectory(output, [corpus], dist)).not.toThrow();
    await expect(runAnswerSnapshots([], true)).rejects.toThrow(/requires --corpus-dir/);
    expect(() => discoverPinnedAnswerRoots(output, "not-a-family")).toThrow("Unknown family not-a-family.");
  });

  it("rejects misspelled or incomplete options before indexing", async () => {
    await expect(runAnswerSnapshots(["--chek"])).rejects.toThrow("Unrecognized argument: --chek");
    await expect(runAnswerSnapshots(["--dist"])).rejects.toThrow("Missing value after --dist.");
    await expect(runAnswerSnapshots(["--corpus-dir", "unused"])).rejects.toThrow("Unrecognized argument: --corpus-dir");
  });

  it("pins public goto and import-reference metadata with project-relative paths", async () => {
    const entry = await project({ "source.ts": source, "consumer.ts": consumer });
    const records = await answerProjectRecords(api, entry);
    const importedGoto = records.find((line) => line.startsWith('goto consumer.ts:2:1 "alias"'));
    expect(importedGoto).toContain('via={"exportedName":"caf\\u{e9}","importedFrom":"source.ts"}');
    expect(importedGoto).toContain('prov={"backend":"native","confidence":"high","resolution":"import"}');
    const importReference = records.find(
      (line) => line.startsWith("ref source.ts:") && line.includes('via={"import":'),
    );
    expect(importReference).toContain('"from":"./source"');
    expect(importReference).toContain('"kind":"named"');
    expect(importReference).toContain('"local":"alias"');
    expect(importReference).toContain('"resolved":"source.ts"');
    expect(importReference).not.toContain(entry.directory);
  });

  it("snapshots deduplicated references for parameters, locals, type parameters, aliases and Rust modules", async () => {
    const entry = await project({
      "parameters.py": "def run(value):\n    local = value\n    return local + value\n",
      "generic.ts": "export function identity<T>(value: T): T { return value; }\n",
      "default.js": "function original() {}\nexport default original;\n",
      "consumer.js": 'import renamed from "./default";\nrenamed();\n',
      "lib.rs": "mod util;\npub fn run() { util::work(); }\n",
      "util.rs": "pub fn work() {}\n",
    });
    const records = await answerProjectRecords(api, entry);
    for (const [file, name] of [
      ["parameters.py", "value"],
      ["parameters.py", "local"],
      ["generic.ts", "T"],
      ["default.js", "original"],
      ["lib.rs", "util"],
    ]) {
      expect(
        records.some((line) => line.startsWith(`refs ${file}:`) && line.includes(` "${name}" ->`)),
        `${file}::${name}`,
      ).toBe(true);
    }
    expect(records.some((line) => line.startsWith('refs default.js:1:10-1:18 default "original" ->'))).toBe(true);
    const summaries = records.filter((line) => line.startsWith("refs "));
    const labels = summaries.map((line) => line.split(" -> ")[0]);
    expect(new Set(labels).size).toBe(labels.length);
    const summary = records.find((line) => line.startsWith("project "))!;
    expect(summaries).toHaveLength(Number(/referenceTargets=(\d+)/.exec(summary)![1]));
  });

  it("includes PHP new sites independently of identifier positions", async () => {
    const construction = "  static function make() { return new self(); }";
    const entry = await project({
      "main.php": ["<?php", "class Widget {", construction, "}", "new Widget();", ""].join("\n"),
    });
    const records = await answerProjectRecords(api, entry);
    const keywordColumn = construction.indexOf("new") + 1;
    expect(
      records.some((line) =>
        line.startsWith(`goto main.php:3:${keywordColumn} "new" -> ok main.php:2:7-2:13 class "Widget"`),
      ),
    ).toBe(true);
    expect(records.some((line) => line.startsWith('goto main.php:5:1 "new" -> not_found '))).toBe(true);
    expect(records.some((line) => line.startsWith('goto main.php:5:5 "Widget" -> ok '))).toBe(true);
  });

  it("pins returned reference order rather than hiding it in sorted snapshot lines", async () => {
    const entry = await project({ "source.ts": source, "consumer.ts": consumer });
    const index = await api.buildProjectIndex(entry.directory, { cache: "off", threads: 1, useNativeWorkers: false });
    const sourceModule = [...index.byFile.values()].find((module) => module.file.endsWith("/source.ts"))!;
    const result = await api.findReferences(index, { def: sourceModule.locals[0] });
    expect(result.status).toBe("ok");
    if (result.status !== "ok") throw new Error("Expected actual source references");
    const records = await answerProjectRecords(api, entry);
    for (const [order, reference] of result.references.entries()) {
      const file = path.relative(entry.directory, reference.file).split(path.sep).join("/");
      const start = reference.range.start;
      const end = reference.range.end;
      const site = ` -> ${file}:${start.line}:${start.column}-${end.line}:${end.column} order=${order}`;
      expect(records.some((line) => line.startsWith("ref source.ts:") && line.includes(site))).toBe(true);
    }
  });

  it("normalizes NFC/NFD filesystem spellings for Cafe.java and cafe-Japanese.ts, not source identifiers", async () => {
    const files = {
      "Caf\u00e9.java": "class Caf\u00e9 { static int read() { return 1; } }\n",
      "caf\u00e9-\u65e5\u672c.ts": "export const value = 1;\nvalue;\n",
    };
    const composed = await project(files);
    const decomposed = await project(
      Object.fromEntries(Object.entries(files).map(([name, text]) => [name.normalize("NFD"), text])),
    );
    const before = await generateAnswerSnapshots(api, group(composed));
    const after = await generateAnswerSnapshots(api, group(decomposed));
    expect(after).toEqual(before);
    expect(after.get("test.txt")).toContain("Caf\\u{e9}.java");
    expect(after.get("test.txt")).toContain("caf\\u{e9}-\\u{65e5}\\u{672c}.ts");
  });

  it("matches absolute path segments without rejecting relative src components or doubled labels", () => {
    const patterns = absoluteSnapshotPathPatterns(["/src", "E:\\repo"]);
    const leaked = (record: string) => patterns.some((pattern) => pattern.test(record));
    expect(leaked("goto lib/src/file.ts:1:1")).toBe(false);
    expect(leaked('goto file.ts:1:1 "lib/src/name"')).toBe(false);
    expect(leaked("goto /src-other/file.ts:1:1")).toBe(false);
    expect(leaked('via={"resolved":"E:/repository/file.ts"}')).toBe(false);
    expect(leaked("goto /src/file.ts:1:1")).toBe(true);
    expect(leaked('via={"resolved":"/src/file.ts"}')).toBe(true);
    expect(leaked("goto E:/repo/file.ts:1:1")).toBe(true);
    expect(leaked("goto E:\\repo\\file.ts:1:1")).toBe(true);
  });

  it("rejects generation when a real indexed project's absolute path leaks into a record", async () => {
    const entry = await project({ "source.ts": "export const value = 1;\nvalue;\n" });
    const leaked = { ...entry, label: `${entry.directory.split(path.sep).join("/")}/leaked` };
    await expect(generateAnswerSnapshots(api, group(leaked))).rejects.toThrow(
      /An answer contains an absolute checkout path/,
    );
    await expect(generateAnswerSnapshots(api, group(entry))).resolves.toHaveProperty("size", 1);
  });

  it("refuses unrelated text files before making any snapshot writes", async () => {
    const output = await roots.create("cg-answer-write-guard-");
    const original = `${generatedHeader}old\n`;
    fs.writeFileSync(path.join(output, "test.txt"), original);
    fs.writeFileSync(path.join(output, "notes.txt"), "not a snapshot\n");
    expect(() => updateAnswerSnapshots(new Map([["test.txt", `${generatedHeader}new\n`]]), output)).toThrow(
      /unrelated .txt file notes.txt/,
    );
    expect(fs.readFileSync(path.join(output, "test.txt"), "utf8")).toBe(original);
    expect(fs.readFileSync(path.join(output, "notes.txt"), "utf8")).toBe("not a snapshot\n");
  });

  it("resolves an explicit relative output directory against cwd, not the source checkout", async () => {
    const cwd = process.cwd();
    const external = await roots.create("cg-answer-cwd-");
    fs.mkdirSync(path.join(external, "answers"));
    fs.writeFileSync(path.join(external, "answers", "notes.txt"), "keep me\n");
    try {
      process.chdir(external);
      await expect(runAnswerSnapshots(["--dir", "answers"])).rejects.toThrow(/unrelated .txt file notes.txt/);
    } finally {
      process.chdir(cwd);
    }
    expect(fs.readFileSync(path.join(external, "answers", "notes.txt"), "utf8")).toBe("keep me\n");
  });

  it("reports grouped added/removed counts, CRLF and missing-newline changes without bare plus lines", async () => {
    const output = await roots.create("cg-answer-diff-");
    const snapshots = new Map([["test.txt", `${generatedHeader}a\nb\n`]]);
    vi.spyOn(console, "log").mockImplementation(() => {});
    const error = vi.spyOn(console, "error").mockImplementation(() => {});
    updateAnswerSnapshots(snapshots, output);
    fs.writeFileSync(path.join(output, "test.txt"), `${generatedHeader}removed\nz\n`);
    expect(() => updateAnswerSnapshots(snapshots, output, true)).toThrow(/stale/);
    const diff = String(error.mock.calls[0][0]);
    expect(diff).toContain("2 added, 2 removed");
    expect(diff.indexOf("  - z")).toBeLessThan(diff.indexOf("  + a"));
    fs.writeFileSync(path.join(output, "test.txt"), `${generatedHeader}a\nb\n`.replaceAll("\n", "\r\n"));
    expect(() => updateAnswerSnapshots(snapshots, output, true)).toThrow(/stale/);
    expect(error.mock.calls.flat().join("\n")).toContain("CRLF line endings");
    fs.writeFileSync(path.join(output, "test.txt"), `${generatedHeader}a\nb`);
    expect(() => updateAnswerSnapshots(snapshots, output, true)).toThrow(/stale/);
    expect(error.mock.calls.flat().join("\n")).toContain("Missing final newline");
    expect(error.mock.calls.flat().join("\n")).not.toMatch(/^\s+\+\s*$/m);
    updateAnswerSnapshots(snapshots, output);
    fs.writeFileSync(path.join(output, "obsolete.txt"), `${generatedHeader}old\n`);
    error.mockClear();
    expect(() => updateAnswerSnapshots(snapshots, output, true)).toThrow(/stale/);
    expect(error.mock.calls).toEqual([["obsolete.txt: obsolete snapshot"]]);
  });

  it("checks an injected real corpus manifest against commit pins and include/exclude scopes", async () => {
    const fixture = await pinnedProject();
    const found = discoverPinnedAnswerRoots(fixture.corpusDir, "fixture", fixture.manifest);
    expect(found[0].projects[0].directory).toBe(fixture.directory);
    expect(found[0].projects[0].buildOptions.discovery).toEqual({
      includeGlobs: ["*.ts"],
      ignoreGlobs: ["ignored/**"],
    });
    const wrong = [{ ...fixture.manifest[0], commit: "0".repeat(40) }];
    expect(() => discoverPinnedAnswerRoots(fixture.corpusDir, "fixture", wrong)).toThrow(
      /tiny: expected pinned commit/,
    );
  });

  it.each(["unstaged", "staged", "untracked"])("rejects %s corpus changes with the corpus name", async (change) => {
    const fixture = await pinnedProject();
    const file = change === "untracked" ? "extra.ts" : "tracked.ts";
    fs.writeFileSync(path.join(fixture.directory, file), "export const changed = 2;\n");
    if (change === "staged") runGit(fixture.directory, ["add", "tracked.ts"]);
    const reason = change === "untracked" ? /tiny: untracked inputs/ : /tiny: tracked inputs differ from pinned commit/;
    expect(() => discoverPinnedAnswerRoots(fixture.corpusDir, "fixture", fixture.manifest)).toThrow(reason);
  });

  it("rejects ancestor, nonexistent child and aliased output paths into a pinned corpus", async () => {
    const fixture = await pinnedProject();
    const output = await roots.create("cg-answer-alias-");
    expect(() => assertAnswerScratchDirectory(fixture.corpusDir, [fixture.directory], snapshotDist)).toThrow(
      /scratch --dir outside/,
    );
    expect(() =>
      assertAnswerScratchDirectory(
        path.join(fixture.directory, "not-created", "answers"),
        [fixture.directory],
        snapshotDist,
      ),
    ).toThrow(/scratch --dir outside/);
    const alias = path.join(output, "alias");
    try {
      fs.symlinkSync(fixture.directory, alias, "dir");
    } catch (error) {
      if (isSymlinkUnavailable(error)) return;
      throw error;
    }
    try {
      expect(() =>
        assertAnswerScratchDirectory(path.join(alias, "answers"), [fixture.directory], snapshotDist),
      ).toThrow(/scratch --dir outside/);
    } finally {
      fs.unlinkSync(alias);
    }
  });

  it("retains runtime and family options in pinned check hints and describes pinned grouping in help", async () => {
    const fixture = await pinnedProject();
    const output = await roots.create("cg-answer-pinned-output-");
    const log = vi.spyOn(console, "log").mockImplementation(() => {});
    vi.spyOn(console, "error").mockImplementation(() => {});
    const args = ["--corpus-dir", fixture.corpusDir, "--dir", output, "--dist", snapshotDist, "--families", "fixture"];
    await runAnswerSnapshots(args, true, fixture.manifest);
    fs.appendFileSync(path.join(output, "tiny.txt"), "# changed\n");
    await expect(runAnswerSnapshots([...args, "--check"], true, fixture.manifest)).rejects.toThrow(
      /--dist.*--families.*fixture/,
    );
    await runAnswerSnapshots(["--help"], true);
    const help = log.mock.calls.flat().join("\n");
    expect(help).toContain("per selected pinned corpus");
    expect(help).not.toContain("per samples project");
  });

  it("fails when snapshot roots omit registered languages", async () => {
    await expect(generateAnswerSnapshots(api, [], true)).rejects.toThrow(
      /No answer snapshot project indexes registered language/,
    );
  });
});
