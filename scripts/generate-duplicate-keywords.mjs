import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const SOURCE_PATH = path.resolve("packages/codegraph-native/src/duplicate_keywords.txt");
const TS_TARGET = path.resolve("src/duplicate-keywords.ts");
const RUST_TARGET = path.resolve("packages/codegraph-native/src/duplicate_keywords.rs");
const CHECK_ONLY = process.argv.includes("--check");

const source = await fs.readFile(SOURCE_PATH, "utf8");
const keywords = parseKeywords(source);
const tsOutput = renderTypeScript(keywords);
const rustOutput = renderRust(keywords);

if (CHECK_ONLY) {
  await assertMatches(TS_TARGET, tsOutput);
  await assertMatches(RUST_TARGET, rustOutput);
} else {
  await fs.writeFile(TS_TARGET, tsOutput, "utf8");
  await fs.writeFile(RUST_TARGET, rustOutput, "utf8");
}

function parseKeywords(text) {
  const keywords = text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);
  const sorted = [...keywords].sort();
  if (keywords.join("\n") !== sorted.join("\n")) {
    throw new Error(`${path.relative(process.cwd(), SOURCE_PATH)} must stay sorted ascending.`);
  }
  const unique = new Set(keywords);
  if (unique.size !== keywords.length) {
    throw new Error(`${path.relative(process.cwd(), SOURCE_PATH)} must not contain duplicates.`);
  }
  return keywords;
}

function renderTypeScript(keywords) {
  const items = keywords.map((keyword) => `  ${JSON.stringify(keyword)},`).join("\n");
  return `// Generated by scripts/generate-duplicate-keywords.mjs from packages/codegraph-native/src/duplicate_keywords.txt\nexport const DUPLICATE_IDENTIFIER_KEYWORDS = [\n${items}\n] as const;\n\nexport const duplicateIdentifierKeywords = new Set<string>(DUPLICATE_IDENTIFIER_KEYWORDS);\n`;
}

function renderRust(keywords) {
  const items = keywords.map((keyword) => `    ${JSON.stringify(keyword)},`).join("\n");
  return `// Generated by scripts/generate-duplicate-keywords.mjs from packages/codegraph-native/src/duplicate_keywords.txt\nuse std::collections::HashSet;\nuse std::sync::LazyLock;\n\npub static DUPLICATE_IDENTIFIER_KEYWORDS: LazyLock<HashSet<&'static str>> = LazyLock::new(|| {\n  HashSet::from([\n${items}\n  ])\n});\n`;
}

async function assertMatches(targetPath, expected) {
  const actual = await fs.readFile(targetPath, "utf8");
  if (actual !== expected) {
    throw new Error(`${path.relative(process.cwd(), targetPath)} is out of date. Run node ./scripts/generate-duplicate-keywords.mjs`);
  }
}
