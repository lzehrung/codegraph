import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

// Immutable seeds from the final numeric-era build. New changes add entry files, not numbers.
export const CACHE_EPOCH_BASES = Object.freeze({ core: 175, language: 30 });
export const CACHE_EPOCH_DIRECTORY = "src/indexer/build-cache/epochs";
export const GENERATED_CACHE_EPOCH_MODULE = "src/indexer/build-cache/epochs.generated.ts";
const CACHE_EPOCH_ENTRY_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*\.txt$/;

export function deriveCacheEpoch(kind, entryNames) {
  if (!Object.hasOwn(CACHE_EPOCH_BASES, kind)) throw new Error(`Unknown cache epoch kind: ${kind}`);
  const names = [...entryNames].sort();
  for (let index = 0; index < names.length; index += 1) {
    if (!CACHE_EPOCH_ENTRY_PATTERN.test(names[index]) || names[index] === names[index - 1]) {
      throw new Error(`Invalid or duplicate ${kind} epoch entry: ${names[index]}`);
    }
  }
  const identity = JSON.stringify(["codegraph-cache-epoch-v1", kind, CACHE_EPOCH_BASES[kind], names]);
  const digest = crypto.createHash("sha256").update(identity).digest("hex");
  // Keep manifests and public types numeric. The upper safe-integer half cannot equal a legacy epoch.
  return 0x10000000000000 + Number.parseInt(digest.slice(0, 13), 16);
}

export function readCacheEpochs(rootDir) {
  const epochs = { core: 0, language: 0 };
  for (const kind of Object.keys(CACHE_EPOCH_BASES)) {
    const directory = path.join(rootDir, CACHE_EPOCH_DIRECTORY, kind);
    const names = [];
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const ignoredDotfile = entry.name.startsWith(".") && !/\.(?:md|txt)$/i.test(entry.name);
      if (ignoredDotfile) continue;
      if (!CACHE_EPOCH_ENTRY_PATTERN.test(entry.name)) {
        throw new Error(
          `Invalid ${kind} epoch entry name: ${entry.name}; expected <slug>.txt using [a-z0-9]+(-[a-z0-9]+)*.`,
        );
      }
      if (!entry.isFile()) throw new Error(`Cache epoch entry must be a regular file: ${kind}/${entry.name}`);
      const reason = fs.readFileSync(path.join(directory, entry.name), "utf8").replaceAll("\r\n", "\n");
      if (!/^[^\r\n]+\n?$/.test(reason) || !reason.trim()) {
        throw new Error(`${kind}/${entry.name}: expected one nonempty line explaining cache invalidation.`);
      }
      names.push(entry.name);
    }
    epochs[kind] = deriveCacheEpoch(kind, names);
  }
  return epochs;
}

export function generateCacheEpochs(rootDir) {
  const epochs = readCacheEpochs(rootDir);
  const source = [
    "// Generated by scripts/generate-cache-epochs.mjs. Do not edit or commit.",
    `export const CORE_ALGORITHM_EPOCH: number = ${epochs.core};`,
    `export const LANGUAGE_BEHAVIOR_EPOCH: number = ${epochs.language};`,
    "",
  ].join("\n");
  const target = path.join(rootDir, GENERATED_CACHE_EPOCH_MODULE);
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== source) fs.writeFileSync(target, source);
  return epochs;
}
